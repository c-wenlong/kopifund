"""G17: write apps/web/src/types.gen.ts from server/finance/types.py and serve.py.

    python3 -m finance.gen_types            # write it (make types)
    python3 -m finance.gen_types --check    # exit 1 when the file is not what this writes

Every TypedDict and every `type X = ...` alias defined in server/finance/types.py
becomes an exported TypeScript type of the same name, in the same order, with
its docstring as the comment (and a key's own string as its comment, "Deprecated"
marking it @deprecated). A TypedDict built on another becomes
`Base & { ... }`; a NotRequired key is optional (`key?:`). serve.py's CACHED,
CACHED_PREFIX and NO_CHANGE follow as constants, so the app caches and
revalidates exactly what the server says. Stdlib only.
"""
import ast
import inspect
import json
import sys
import typing
from pathlib import Path

from . import types as wire

ROOT = Path(__file__).resolve().parents[2]     # the repository root
OUT = ROOT / "apps" / "web" / "src" / "types.gen.ts"

HEADER = """\
// Generated by `python3 -m finance.gen_types` from server/finance/types.py and serve.py.
// Do not edit by hand: change those, then run `make types`.
// server/tests/test_types.py fails while this file differs from what that writes.
"""

# a NewType is a type the app already has, imported from where it lives
NEW_TYPES = {"Cents": "./money"}
SCALARS = {str: "string", int: "number", float: "number", bool: "boolean", type(None): "null",
           typing.Any: "unknown"}


def _named(tp):
    """True for a type server/finance/types.py defines and the file exports by name."""
    return getattr(tp, "__module__", None) == wire.__name__ and (
        isinstance(tp, typing.TypeAliasType) or typing.is_typeddict(tp))


def ts(tp) -> str:
    """The TypeScript for one Python annotation."""
    if isinstance(tp, typing.NewType):
        if tp.__name__ not in NEW_TYPES:
            raise TypeError(f"{tp.__name__}: add it to NEW_TYPES with the module the app keeps it in")
        return tp.__name__
    if _named(tp):
        return tp.__name__
    if tp in SCALARS:
        return SCALARS[tp]
    origin, args = typing.get_origin(tp), typing.get_args(tp)
    if origin is list:
        inner = ts(args[0])
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if origin is dict:
        return f"Record<{ts(args[0])}, {ts(args[1])}>"
    if origin is typing.Literal:
        if not all(isinstance(a, (str, int, bool)) for a in args):
            raise TypeError(f"{tp!r}: a Literal holds strings, numbers or booleans")
        return " | ".join(json.dumps(a) for a in args)
    if origin is typing.Union:
        return " | ".join(ts(a) for a in args)
    raise TypeError(f"no TypeScript for {tp!r}")


def _comment(doc, indent=""):
    if not doc:
        return ""
    lines = inspect.cleandoc(doc).splitlines()
    if any("*/" in line for line in lines):
        raise ValueError("a docstring holds */, which would end the comment early")
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {line}".rstrip() + "\n" for line in lines) + f"{indent} */\n"


def _alias_docs():
    """{alias name: the string right after its `type X = ...` line}."""
    body = ast.parse(Path(wire.__file__).read_text(encoding="utf-8")).body
    docs = {}
    for node, after in zip(body, body[1:]):
        if (isinstance(node, ast.TypeAlias) and isinstance(after, ast.Expr)
                and isinstance(after.value, ast.Constant) and isinstance(after.value.value, str)):
            docs[node.name.id] = after.value.value
    return docs


def _field_docs():
    """{(class name, key): the string right under that key in its TypedDict}."""
    body = ast.parse(Path(wire.__file__).read_text(encoding="utf-8")).body
    docs = {}
    for cls in body:
        if not isinstance(cls, ast.ClassDef):
            continue
        for node, after in zip(cls.body, cls.body[1:]):
            if (isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)
                    and isinstance(after, ast.Expr) and isinstance(after.value, ast.Constant)
                    and isinstance(after.value.value, str)):
                docs[cls.name, node.target.id] = after.value.value
    return docs


def _field_comment(doc):
    """G17: a key's own comment; one that starts "Deprecated" is @deprecated."""
    if not doc:
        return ""
    text = " ".join(inspect.cleandoc(doc).split())
    if text.startswith("Deprecated"):
        text = "@deprecated " + text.removeprefix("Deprecated").lstrip(":, ")
    return _comment(text, "  ")


def _typeddict(cls) -> str:
    hints = typing.get_type_hints(cls)
    bases = [b for b in getattr(cls, "__orig_bases__", ()) if typing.is_typeddict(b)]
    inherited = set().union(*(typing.get_type_hints(b) for b in bases)) if bases else set()
    docs = _field_docs()
    fields = "".join(f"{_field_comment(docs.get((cls.__name__, k)))}"
                     f"  {k}{'?' if k in cls.__optional_keys__ else ''}: {ts(v)};\n"
                     for k, v in hints.items() if k not in inherited)
    head = "".join(f"{b.__name__} & " for b in bases)
    return f"export type {cls.__name__} = {head}{{\n{fields}}};\n"


def _strings(name, doc, values) -> str:
    items = "".join(f"  {json.dumps(v)},\n" for v in sorted(values))
    return f"{_comment(doc)}export const {name}: readonly string[] = [\n{items}];\n"


def render() -> str:
    """The whole of apps/web/src/types.gen.ts."""
    import serve
    docs = _alias_docs()
    parts = [HEADER, "".join(f'import type {{ {n} }} from "{m}";\n' for n, m in sorted(NEW_TYPES.items()))]
    for name, value in vars(wire).items():
        if not _named(value) or value.__name__ != name:
            continue
        if isinstance(value, typing.TypeAliasType):
            parts.append(f"{_comment(docs.get(name))}export type {name} = {ts(value.__value__)};\n")
        else:
            parts.append(_comment(value.__doc__) + _typeddict(value))
    parts.append(_strings("CACHED_PATHS", "serve.py, CACHED: the GETs that answer with an ETag; everything "
                                          "else is asked afresh every time.", serve.CACHED))
    parts.append(f"/** serve.py, CACHED_PREFIX: every stat's own result is cached too. */\n"
                 f"export const CACHED_PREFIX = {json.dumps(serve.CACHED_PREFIX)};\n")
    parts.append(_strings("NO_CHANGE_PATHS", "serve.py, NO_CHANGE: the writes that change nothing a GET reads, "
                                             "so no view reloads after them.", serve.NO_CHANGE))
    reread = "".join(f"  {json.dumps(k)}: {json.dumps(sorted(v))},\n" for k, v in sorted(serve.REREAD_AFTER.items()))
    parts.append(f"{_comment('serve.py, REREAD_AFTER (G18): the GETs a view asks for again after one of those writes.')}"
                 f"export const REREAD_AFTER: Readonly<Record<string, readonly string[]>> = {{\n{reread}}};\n")
    return "\n".join(parts)


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run `make types`", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
