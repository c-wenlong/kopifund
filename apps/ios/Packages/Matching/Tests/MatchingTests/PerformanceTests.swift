import XCTest
@testable import Matching

/// G24: a long alert used to take seconds to open because `detect` asked
/// `Dates.detectFormat` for thousands of token windows and each ask compiled
/// up to ten fresh regexes. These bounds sit far above the fixed cost (a few
/// ms) and far below the broken one (about a second on this class of
/// machine), so a real regression trips them while CI noise does not.
final class PerformanceTests: XCTestCase {

    /// A synthesised multi-KB bank alert, flattened to one line the way some
    /// sources hand it over: the worst shape for the date-window scan, since
    /// every token then has five windows to try. Invented bank, invented
    /// numbers, never a real inbox or statement.
    static let oneLineAlert: String = {
        let head = "Subject: Transaction Alert " +
            "You charged SGD 48.20 at FAIRMART FINEST SINGAPORE on 27 Oct 2026 14:32:11. " +
            "Card ending 4821. Reference TT26027123456. "
        var footer = ""
        let para = "This message was auto-generated by Merlion Bank Ltd. " +
            "Please do not reply to this e-mail. If you did not authorise this transaction, " +
            "please call our 24-hour hotline at 1800 555 0199 immediately. " +
            "Unsubscribe from marketing mail in your settings page. " +
            "All rights reserved. Confidentiality notice: this e-mail is intended " +
            "for the named recipient only and may contain privileged information. "
        while head.count + footer.count < 4200 { footer += para }
        return head + footer + "Merlion Bank Ltd, 1 Raffles Quay, Singapore 048583."
    }()

    func test_detect_on_a_long_single_line_alert_stays_fast() {
        let text = Self.oneLineAlert
        let tokens = Tokenizer.tokenize(text)
        var cands: [Candidate] = []
        let elapsed = ContinuousClock().measure {
            cands = Candidates.detect(in: text, tokens: tokens)
        }
        // the fixed scan takes single-digit ms here; 0.5s leaves wide margin
        // for a slow CI box while still catching the regex-per-window bug
        XCTAssertLessThan(elapsed, .milliseconds(500))
        XCTAssertTrue(cands.contains { $0.field == .amount && $0.confident })
        XCTAssertTrue(cands.contains { $0.field == .date && $0.confident })
    }

    func test_boilerplate_token_indexes_on_a_long_single_line_alert_stays_fast() {
        // sixfold the realistic alert: the old per-token line scan was
        // quadratic, so at this size it needs seconds where the single pass
        // needs a millisecond, and the bound separates them on any box
        let text = String(repeating: Self.oneLineAlert + " ", count: 6)
        let tokens = Tokenizer.tokenize(text)
        let elapsed = ContinuousClock().measure {
            _ = AlertText.boilerplateTokenIndexes(in: text, tokens: tokens)
        }
        XCTAssertLessThan(elapsed, .milliseconds(500))
    }
}
